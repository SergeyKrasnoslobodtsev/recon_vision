"""Тесты нормализатора текста и парсера валюты."""

import pytest

from extractor.normalize import transform_currency, transform_text


class TestTransformText:
    def test_empty(self):
        assert transform_text("") == ""

    @pytest.mark.parametrize(
        "text, expected",
        [
            ("текст", "ТЕКСТ"),
            ("ТЕКСТ", "ТЕКСТ"),
            ("Текст", "ТЕКСТ"),
        ],
    )
    def test_uppercase(self, text, expected):
        assert transform_text(text) == expected

    # ------------------------------------------------------------------
    # Расширенная кириллица -> русская (ручной маппинг)
    # ------------------------------------------------------------------
    @pytest.mark.parametrize(
        "text, expected",
        [
            ("РЎСАЛ", "РУСАЛ"),  # Ў (U+040E) -> У  белорусский
            ("ўсал", "УСАЛ"),  # ў (U+045E) -> У
            ("раҙвернутое", "РАЗВЕРНУТОЕ"),  # ҙ (U+0499) -> З  (uppercase Ҙ U+0498)
            ("Џел", "ТЕЛ"),  # Џ (U+040F) -> Т  сербский
            ("развернүтое", "РАЗВЕРНУТОЕ"),  # ү (U+04AF) -> У  казахский
            ("Леснӥд", "ЛЕСНИД"),  # ӥ (U+04E5) -> И
            ("Қазақ", "КАЗАК"),  # Қ -> К, қ -> К
            ("Ңурлан", "НУРЛАН"),  # Ң -> Н
            ("Ғалым", "ГАЛЫМ"),  # Ғ -> Г
            ("ёжик", "ЕЖИК"),  # Ё -> Е
        ],
    )
    def test_extended_cyrillic_manual(self, text, expected):
        assert transform_text(text) == expected

    # ------------------------------------------------------------------
    # Расширенная кириллица -> русская (автоматически через NFD)
    # ------------------------------------------------------------------
    @pytest.mark.parametrize(
        "text, expected",
        [
            ("Ӧ", "О"),  # O WITH DIAERESIS (U+04E6)
            ("ӧ", "О"),  # o WITH DIAERESIS (U+04E7)
            ("Ӓ", "А"),  # A WITH DIAERESIS (U+04D2)
            ("Ӗ", "Е"),  # IE WITH BREVE    (U+04D6)
        ],
    )
    def test_extended_cyrillic_nfd(self, text, expected):
        assert transform_text(text) == expected

    # ------------------------------------------------------------------
    # Латиница -> кириллица в кириллическом контексте
    # ------------------------------------------------------------------
    @pytest.mark.parametrize(
        "text, expected",
        [
            ("САЛЬДOНА", "САЛЬДОНА"),  # Latin O внутри кирилл. слова -> Р
            ("PЕРIОД", "РЕРIОД"),  # P -> Р, но I не в _LAT_TO_CYR — остаётся
            ("НКАЗ", "НКАЗ"),  # уже кириллица, без изменений
        ],
    )
    def test_smart_lat_to_cyrillic(self, text, expected):
        assert transform_text(text) == expected

    # ------------------------------------------------------------------
    # O/I -> 0/1 в числовом контексте
    # ------------------------------------------------------------------
    @pytest.mark.parametrize(
        "text, expected",
        [
            ("21.OI.2025", "21.01.2025"),  # дата с OCR-мусором
            ("0.OO", "0.00"),  # сумма
            ("1OO,OO", "100,00"),  # сумма с кириллическим О
        ],
    )
    def test_numeric_ocr_fix(self, text, expected):
        assert transform_text(text) == expected

    # ------------------------------------------------------------------
    # ООО — форма собственности
    # ------------------------------------------------------------------
    @pytest.mark.parametrize(
        "text, expected",
        [
            ('000 "Ромашка"', 'ООО "РОМАШКА"'),  # стандартный случай
            ('000."Ромашка"', 'ООО. "РОМАШКА"'),  # точка перед кавычкой
            ("000 РОМАШКА", "ООО РОМАШКА"),  # без кавычек
            ('000."Юнигрин"', 'ООО. "ЮНИГРИН"'),
        ],
    )
    def test_ooo_company(self, text, expected):
        assert transform_text(text) == expected

    @pytest.mark.parametrize(
        "text, expected",
        [
            ("20 000.25", "20 000.25"),  # тысячный разделитель, не трогаем
            ("20 ООО.25", "20 000.25"),  # кириллические О — тоже защищаем
        ],
    )
    def test_ooo_thousands_protected(self, text, expected):
        assert transform_text(text) == expected

    # ------------------------------------------------------------------
    # Нормализация дат
    # ------------------------------------------------------------------
    @pytest.mark.parametrize(
        "text, expected",
        [
            ("31,03.2025", "31.03.2025"),  # запятая как разделитель
            ("01,11:2024", "01.11.2024"),  # разные разделители
            ("16.11.2022", "16.11.2022"),  # уже корректная дата
            ("01.04.2025г.", "01.04.2025 Г."),  # суффикс г.
            ("01.04.2025r.", "01.04.2025 Г."),  # суффикс r. (OCR)
            ("01.01.2025Г.", "01.01.2025 Г."),  # суффикс Г. без пробела
        ],
    )
    def test_date_normalization(self, text, expected):
        assert transform_text(text) == expected

    # ------------------------------------------------------------------
    # Пробельные правила
    # ------------------------------------------------------------------
    @pytest.mark.parametrize(
        "text, expected",
        [
            ("слово  следующее", "СЛОВО СЛЕДУЮЩЕЕ"),
            ("слово     следующее", "СЛОВО СЛЕДУЮЩЕЕ"),
            ("слово следующее,прочее", "СЛОВО СЛЕДУЮЩЕЕ, ПРОЧЕЕ"),
            ("слово следующее:прочее", "СЛОВО СЛЕДУЮЩЕЕ: ПРОЧЕЕ"),
            ("слово следующее;прочее", "СЛОВО СЛЕДУЮЩЕЕ; ПРОЧЕЕ"),
        ],
    )
    def test_space_rules(self, text, expected):
        assert transform_text(text) == expected

    @pytest.mark.parametrize(
        "text, expected",
        [
            ("слово,следующее", "СЛОВО, СЛЕДУЮЩЕЕ"),
            ("слово ,следующее", "СЛОВО, СЛЕДУЮЩЕЕ"),
            ("в лице ,", "В ЛИЦЕ,"),
            ("3,5", "3,5"),  # дробь — пробел не добавляется
        ],
    )
    def test_comma_spacing(self, text, expected):
        assert transform_text(text) == expected

    @pytest.mark.parametrize(
        "text, expected",
        [
            ("84/22.от", "84/22. ОТ"),  # пробел после точки перед буквой
            ("слово.следующее", "СЛОВО. СЛЕДУЮЩЕЕ"),
            ("16.11.2022", "16.11.2022"),  # дата — без пробела
            ("т.ч.", "Т.Ч."),  # аббревиатура — без пробела
            ("т.д.", "Т.Д."),
            ("н.н.", "Н.Н."),
            ("в т. ч. ндс", "В Т. Ч. НДС"),
            # пробел не добавляется: перед точкой одна буква после пробела
            ("Иванов Н.Н.предложил", "ИВАНОВ Н.Н.ПРЕДЛОЖИЛ"),
        ],
    )
    def test_dot_spacing(self, text, expected):
        assert transform_text(text) == expected

    # ------------------------------------------------------------------
    # Кавычки
    # ------------------------------------------------------------------
    @pytest.mark.parametrize(
        "text, expected",
        [
            ("«СЛОВО»", '"СЛОВО"'),
            ('"СЛОВО"', '"СЛОВО"'),  # типографские -> стандартные
            ('ООО"Ромашка"', 'ООО "РОМАШКА"'),  # пробел перед открывающей
            ('АО "ЕВРОСИБЭНЕРГО"', 'АО "ЕВРОСИБЭНЕРГО"'),  # закрывающая — без пробела
            ('""слово""', '"СЛОВО"'),  # двойные кавычки -> одна
        ],
    )
    def test_quote_normalization(self, text, expected):
        assert transform_text(text) == expected

    # ------------------------------------------------------------------
    # OCR-артефакты
    # ------------------------------------------------------------------
    @pytest.mark.parametrize(
        "text, expected",
        [
            ("за период·с", "ЗА ПЕРИОД С"),  # · (U+00B7) -> пробел
            ("' 3 'КВАРТАЛ", "3 КВАРТАЛ"),  # апостроф -> пробел + collapse
            ("'СЛОВО'", "СЛОВО"),  # типографские одиночные кавычки
            # ("текст\nпродолжение", "ТЕКСТ ПРОДОЛЖЕНИЕ"),  # \n -> пробел
        ],
    )
    def test_ocr_artifacts(self, text, expected):
        assert transform_text(text) == expected

    # ------------------------------------------------------------------
    # Ведущая пунктуация
    # ------------------------------------------------------------------
    @pytest.mark.parametrize(
        "text, expected",
        [
            (".0.00", "0.00"),  # ведущая точка
            (":9 392 200.36", "9 392 200.36"),  # ведущее двоеточие
            ("Т.Г:", "Т.Г:"),  # двоеточие после буквы — не трогаем
        ],
    )
    def test_leading_punct(self, text, expected):
        assert transform_text(text) == expected

    # ------------------------------------------------------------------
    # Дублирующаяся пунктуация
    # ------------------------------------------------------------------
    @pytest.mark.parametrize(
        "text, expected",
        [
            ("слово, , следующее", "СЛОВО, СЛЕДУЮЩЕЕ"),
            ("слово,, следующее", "СЛОВО, СЛЕДУЮЩЕЕ"),
            ("слово;; следующее", "СЛОВО; СЛЕДУЮЩЕЕ"),
            ("слово.. следующее", "СЛОВО. СЛЕДУЮЩЕЕ"),
            ("слово; ; следующее", "СЛОВО; СЛЕДУЮЩЕЕ"),
        ],
    )
    def test_collapse_dup_punct(self, text, expected):
        assert transform_text(text) == expected


class TestTransformCurrency:
    @pytest.mark.parametrize(
        "value, expected",
        [
            ("1 649 669,47", 1649669.47),
            ("47 761,70", 47761.70),
            ("23 035 017,97", 23035017.97),
            ("0,00", 0.0),
            ("100", 1.0),
            ("10000", 100.0),
            ("1 649 669,4О", 1649669.40),  # кириллическая О -> 0
            ("", 0.0),
            ("-", 0.0),
            ("—", 0.0),
            ("–", 0.0),
            (None, 0.0),
        ],
    )
    def test_parse(self, value, expected):
        assert transform_currency(value) == pytest.approx(expected)

    def test_raises_on_non_numeric(self):
        with pytest.raises(ValueError):
            transform_currency("abc")
