import pytest

from vision_core.utils.currency import parse_currency


@pytest.mark.parametrize(
    "value, expected",
    [
        # Чистые цифры
        ("123456789", 1234567.89),
        ("12345", 123.45),
        ("123", 1.23),
        ("12", 0.12),
        ("1", 0.01),
        ("0", 0.00),
        ("00", 0.00),
        ("000", 0.00),
        ("100", 1.00),
        ("1000", 10.00),
        ("10000", 100.00),
        # Различные форматы разделителей
        ("1.234.567,89", 1234567.89),
        ("1,234,567.89", 1234567.89),
        ("1 234 567,89", 1234567.89),
        ("1.234.567,89руб.", 1234567.89),
        ('19 660 789,55"', 19660789.55),
        # Символы валюты и мусор
        ("$12345", 123.45),
        ("€12345", 123.45),
        ("¥12345", 123.45),
        ("12345 руб.", 123.45),
        (";12345/[<]", 123.45),
        # Знак минус игнорируется (OCR-артефакт)
        ("-12345", 123.45),
        # OCR-замены: кириллическая О и латинская l -> цифры
        ("1 649 669,4О", 1649669.40),
        ("l 000,00", 1000.00),
        # Пустые и прочерк -> 0.0
        ("", 0.0),
        ("-", 0.0),
        ("—", 0.0),
        (None, 0.0),
        ("–", 0.0),
    ],
)
def test_parse_currency(value, expected):
    assert parse_currency(value) == pytest.approx(expected)


def test_parse_currency_raises_on_non_numeric_nonempty():
    with pytest.raises(ValueError):
        parse_currency("abc")
